"""Candidate generation for the bounded search (README: 'Suggested search strategy').

Only single-setting performance-directed changes are generated by default,
plus one optional combined trial of the individually winning settings (a
'small, known-related group'). Candidates are ranked so settings that load
the estimated bottleneck are tried first. The list is bounded by the search
budget — never exhaustive.
"""

from __future__ import annotations

from optimize.models import Candidate, SettingsCatalog, SettingSpec, SettingsState


def _current_value(spec: SettingSpec, settings: SettingsState) -> str:
    return str(settings.get(spec.key, spec.default))


def _cost(spec: SettingSpec, value: str) -> float:
    sv = spec.spec_for(value)
    return sv.gpu_ms + sv.cpu_ms


def generate_candidates(
    catalog: SettingsCatalog,
    current: SettingsState,
    bottleneck: str = "unknown",
    limit: int = 12,
) -> list[Candidate]:
    """One candidate per strictly-cheaper supported value of each setting."""
    candidates: list[Candidate] = []
    for spec in catalog.specs:
        cur = _current_value(spec, current)
        cur_cost = _cost(spec, cur)
        for sv in spec.values:
            if sv.value == cur:
                continue
            new_cost = sv.gpu_ms + sv.cpu_ms
            if new_cost >= cur_cost:
                continue  # performance-directed: only cheaper values are tested
            current_sv = spec.spec_for(cur)
            candidates.append(
                Candidate(
                    label=f"{spec.label}: {cur} -> {sv.value}",
                    changes={spec.key: sv.value},
                    expected_gpu_delta_ms=current_sv.gpu_ms - sv.gpu_ms,
                    expected_cpu_delta_ms=current_sv.cpu_ms - sv.cpu_ms,
                )
            )

    def rank_key(cand: Candidate) -> tuple[int, float]:
        spec = catalog.spec(next(iter(cand.changes)))
        bottleneck_match = 0 if spec.bottleneck == bottleneck else 1
        return (bottleneck_match, -cand.expected_gain_ms)

    candidates.sort(key=rank_key)
    return candidates[:limit]


def combined_candidate(
    catalog: SettingsCatalog,
    base: SettingsState,
    winners: list[Candidate],
) -> Candidate | None:
    """Merge individually winning changes into one small, known-related trial."""
    if len(winners) < 2:
        return None
    changes: dict[str, str] = {}
    for winner in winners:
        changes.update(winner.changes)
    if len(changes) < 2:
        return None

    gpu_delta = cpu_delta = 0.0
    for key, value in changes.items():
        spec = catalog.spec(key)
        cur_sv = spec.spec_for(_current_value(spec, base))
        new_sv = spec.spec_for(value)
        gpu_delta += cur_sv.gpu_ms - new_sv.gpu_ms
        cpu_delta += cur_sv.cpu_ms - new_sv.cpu_ms

    return Candidate(
        label="combined: " + ", ".join(f"{k}={v}" for k, v in sorted(changes.items())),
        changes=changes,
        expected_gpu_delta_ms=gpu_delta,
        expected_cpu_delta_ms=cpu_delta,
    )
