import json

import pytest

from optimize.cli import main
from optimize.reporting import (
    SessionInfo,
    export_profile,
    frame_time_chart_svg,
    load_session,
    render_session_html,
    write_report,
)


def _flat_frames(n: int = 500, ms: float = 8.0) -> list[float]:
    return [ms] * n


def test_chart_contains_frame_times_and_reference_lines():
    frames = _flat_frames()
    frames += [40.0, 45.0]  # a couple of spikes for the p99 line
    svg = frame_time_chart_svg(frames, "Test run")
    assert "<svg" in svg and "polyline" in svg
    assert "mean" in svg and "p99" in svg
    assert "Test run" in svg
    assert "500 stride" not in svg or "stride 1" in svg


def test_chart_downsamples_long_runs():
    svg = frame_time_chart_svg(_flat_frames(5000), "Long run")
    assert "stride 5" in svg  # ceil(5000/1200) = 5
    assert svg.count("polyline") == 1


def test_chart_handles_empty_input():
    assert "no frame-time data" in frame_time_chart_svg([], "Empty")


def test_chart_escapes_html_in_title():
    svg = frame_time_chart_svg(_flat_frames(), "<script>alert(1)</script>")
    assert "<script>" not in svg
    assert "&lt;script&gt;" in svg


@pytest.fixture()
def session_db(tmp_path):
    """A real session produced by the demo loop, via the CLI."""
    assert main(["demo", "--data-dir", str(tmp_path), "--trials", "3", "--runs", "2",
                 "--seconds", "3"]) == 0
    return tmp_path / "profiles.db", tmp_path


def test_load_latest_session(session_db):
    db_path, _ = session_db
    info = load_session(db_path)
    assert info is not None
    assert info.game_id == "aurora-plains"
    assert info.runs and info.trials
    assert info.recommendation in {"apply-candidate", "no-change"}


def test_load_missing_session_raises(session_db):
    db_path, _ = session_db
    with pytest.raises(FileNotFoundError):
        load_session(db_path, session_id=9999)


def test_write_report_contains_charts_and_trials(session_db):
    db_path, _ = session_db
    out = db_path.parent / "reports" / "test.html"
    write_report(db_path, out)
    html = out.read_text()
    assert html.count("<svg") == 2  # baseline + best trial
    assert "Trials" in html
    assert "aurora-plains" in html
    assert "kept" in html or "rejected" in html
    assert "Generated by pc-optimize" in html


def test_render_handles_session_without_best_settings(tmp_path):
    info = SessionInfo(
        session_id=1, ts="2026-01-01T00:00:00", game_id="aurora-plains", goal="balanced",
        bottleneck="gpu", hardware={"gpu_model": "g", "cpu_model": "c"},
        baseline_settings={"shadow_quality": "high"}, best_settings=None,
        baseline_score=0.5, best_score=None, recommendation="benchmark-only",
        applied=False, backup_id=None, notes=[], trials=[],
        runs=[{"label": "baseline", "settings": {}, "metrics": {
            "avg_fps": 66.0, "fps_1p_low": 50.0, "consistency": 0.9},
            "frame_times_ms": _flat_frames()}],
    )
    html = render_session_html(info)
    assert "benchmark-only" in html
    assert "not applied" in html
    assert html.count("<svg") == 1


def test_export_profile_uses_best_when_available(session_db):
    db_path, tmp_path = session_db
    out = tmp_path / "exports" / "profile.json"
    profile = export_profile(db_path, out)
    saved = json.loads(out.read_text())

    info = load_session(db_path)
    expected = info.best_settings or info.baseline_settings
    assert saved["settings"] == expected == profile["settings"]
    assert saved["format"] == "pc-optimize-profile"
    assert saved["game_id"] == "aurora-plains"
    assert isinstance(saved["changed"], list)
